#!/bin/sh
# Compiles src/modelKernels.c (the model's two hot loops) to WebAssembly with SIMD and writes it, as base64, into
# src/modelKernels.ts, which is what the app loads. Needs clang with the wasm32 target and wasm-ld (LLVM 16 or newer).
# Run from web/:  sh scripts/build-kernels.sh
set -e
out=$(mktemp)
clang --target=wasm32 -O3 -msimd128 -nostdlib -ffreestanding -Wl,--no-entry -Wl,--export=__heap_base -Wl,--export-memory -o "$out" src/modelKernels.c
{
  echo "// Generated by scripts/build-kernels.sh from src/modelKernels.c. Do not edit by hand."
  echo "/** The compiled kernels ($(wc -c < "$out" | tr -d ' ') bytes of WebAssembly), base64. */"
  echo "export const KERNELS_WASM = '$(base64 -w0 "$out")';"
} > src/modelKernels.ts
rm "$out"
echo "wrote src/modelKernels.ts"
